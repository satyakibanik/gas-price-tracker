"""Check the public dashboard through Chromium."""
import sys

from playwright.sync_api import expect, sync_playwright


with sync_playwright() as playwright:
    browser = playwright.chromium.launch()
    page = browser.new_page()
    page.goto(sys.argv[1])
    expect(page.locator("#location")).to_have_text("Latham, NY")
    search = page.get_by_role("searchbox", name="Find a fuel center")
    search.fill("North Carolina")
    results = page.locator("#results")
    expect(results.get_by_role("button", name="Charlotte, NC · #6540", exact=False)).to_be_visible()
    expect(results.get_by_role("button", name="Matthews, NC", exact=False)).to_be_visible()
    results.get_by_role("button", name="Charlotte, NC · #6540", exact=False).click()
    expect(page.locator("#location")).to_have_text("Charlotte, NC")
    expect(page.locator("#address")).to_contain_text("JW Clay Blvd", ignore_case=True)
    chart = page.locator("#chart")
    expect(chart).to_be_visible()
    chart.locator("circle").first.hover()
    tooltip = page.locator("#price-tooltip")
    expect(tooltip).to_be_visible()
    expect(tooltip).to_contain_text("Unleaded $")
    expect(tooltip).to_contain_text("Premium $")
    expect(tooltip).to_contain_text("Diesel $")
    search.hover()
    expect(tooltip).to_be_hidden()
    search.fill("no-such-club-00000")
    expect(results).to_contain_text("No matching fuel centers.")
    page.get_by_role("link", name="Map", exact=True).click()
    expect(page.get_by_role("status")).to_have_text("529 of 529 fuel centers on the map")
    expect(page.locator(".leaflet-marker-icon")).to_have_count(529)
    expect(page.locator(".price-legend")).to_contain_text("Latest unleaded price")
    expect(page.locator("#price-update time")).to_be_visible()
    marker = page.locator('.leaflet-marker-icon[title="8909 JW Clay Blvd, Charlotte, NC 28262" i]')
    # Pins overlap at national zoom, so dispatch the click on the selected pin.
    marker.dispatch_event("click")
    popup = page.locator(".leaflet-popup")
    expect(popup).to_contain_text("Unleaded")
    expect(popup.get_by_role("link", name="View price history")).to_have_attribute("href", "./?club=6540")
    popup.get_by_role("link", name="View price history").click()
    expect(page.locator("#location")).to_have_text("Charlotte, NC")
    browser.close()
