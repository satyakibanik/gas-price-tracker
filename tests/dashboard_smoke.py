"""Check the public dashboard through Chromium."""
import sys

from playwright.sync_api import expect, sync_playwright


with sync_playwright() as playwright:
    browser = playwright.chromium.launch()
    page = browser.new_page()
    page.goto(sys.argv[1])
    expect(page.locator("#location")).to_have_text("Latham, NY")
    search = page.get_by_role("searchbox", name="Find a fuel center")
    search.fill("North Carolina")
    results = page.locator("#results")
    expect(results.get_by_role("link", name="Charlotte, NC · #6540", exact=False)).to_be_visible()
    expect(results.get_by_role("link", name="Matthews, NC", exact=False)).to_be_visible()
    results.get_by_role("link", name="Charlotte, NC · #6540", exact=False).click()
    expect(page.locator("#location")).to_have_text("Charlotte, NC")
    expect(page.locator("#address")).to_contain_text("JW Clay Blvd", ignore_case=True)
    chart = page.locator("#chart")
    expect(chart).to_be_visible()
    chart.locator("circle").first.hover()
    tooltip = page.locator("#price-tooltip")
    expect(tooltip).to_be_visible()
    expect(tooltip).to_contain_text("Unleaded $")
    expect(tooltip).to_contain_text("Premium $")
    expect(tooltip).to_contain_text("Diesel $")
    search.hover()
    expect(tooltip).to_be_hidden()
    search.fill("no-such-club-00000")
    expect(results).to_contain_text("No matching fuel centers.")
    page.get_by_role("link", name="Map", exact=True).click()
    expect(page.get_by_role("status")).to_have_text("529 of 529 fuel centers on the map")
    expect(page.locator(".leaflet-marker-icon")).to_have_count(529)
    expect(page.locator(".price-legend")).to_contain_text("Unleaded price / gal")
    expect(page.locator("#price-update time")).to_be_visible()
    marker = page.locator('.leaflet-marker-icon[title="8909 JW Clay Blvd, Charlotte, NC 28262" i]')
    # Pins overlap at national zoom, so dispatch the click on the selected pin.
    marker.dispatch_event("click")
    popup = page.locator(".leaflet-popup")
    grades = [row.split(" · ")[0] for row in popup.locator(".map-popup-prices li").all_text_contents()]
    assert "Unleaded" in grades
    assert grades == [grade for grade in ("Unleaded", "Premium", "Diesel", "Midgrade") if grade in grades]
    expect(popup.get_by_role("link", name="View price history")).to_have_attribute("href", "./?club=6540")
    popup.get_by_role("link", name="View price history").click()
    expect(page.locator("#location")).to_have_text("Charlotte, NC")

    phone = browser.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True)
    mobile_page = phone.new_page()
    mobile_page.goto(sys.argv[1].rstrip("/") + "/?club=6540")
    mobile_chart = mobile_page.locator("#chart")
    dots = mobile_chart.locator("circle")
    expect(dots.first).to_be_visible()
    mobile_chart.scroll_into_view_if_needed()
    bounds = mobile_chart.bounding_box()
    x_positions = dots.evaluate_all("(dots) => dots.map(dot => dot.cx.baseVal.value)")
    left = round(bounds["x"] + min(x_positions) + 2)
    right = round(bounds["x"] + max(x_positions) - 2)
    y = round(bounds["y"] + 25)
    mobile_tooltip = mobile_page.locator("#price-tooltip")
    mobile_page.touchscreen.tap(left, y)
    expect(mobile_tooltip).to_be_visible()
    expect(mobile_tooltip).to_contain_text("Unleaded $")
    start_date = mobile_tooltip.locator("strong").inner_text()
    mobile_page.get_by_role("heading", name="Charlotte, NC").tap()
    expect(mobile_tooltip).to_be_hidden()
    mobile_chart.scroll_into_view_if_needed()
    y = round(mobile_chart.bounding_box()["y"] + 25)
    touch = phone.new_cdp_session(mobile_page)
    touch.send("Input.dispatchTouchEvent", {"type": "touchStart", "touchPoints": [{"x": left, "y": y}]})
    expect(mobile_tooltip).to_be_visible()
    expect(mobile_tooltip.locator("strong")).to_have_text(start_date)
    touch.send("Input.dispatchTouchEvent", {"type": "touchMove", "touchPoints": [{"x": right, "y": y}]})
    expect(mobile_tooltip.locator("strong")).not_to_have_text(start_date)
    expect(mobile_tooltip).to_contain_text("Unleaded $")
    touch.send("Input.dispatchTouchEvent", {"type": "touchEnd", "touchPoints": []})
    expect(mobile_tooltip).to_be_visible()
    phone.close()
    browser.close()
